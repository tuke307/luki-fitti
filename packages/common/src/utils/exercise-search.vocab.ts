/**
 * Vocabulary of the exercise search (`exercise-search.util.ts`). Plain data so the iOS app can use
 * the same rules: `apps/apple/scripts/export-starter-catalog.ts` writes it to `exercise_search.json`.
 *
 * All entries are in folded form: lower case, `ä/ae → a`, `ö/oe → o`, `ü/ue → u`, `ß → ss`, no
 * accents. Phrases run on the folded text (words separated by single spaces or hyphens) and join
 * multi-word names into one canonical token, so "Sit-Ups", "sit ups" and "situp" all become
 * "situp". Synonyms then add canonical tokens for German words, gym slang and abbreviations; the
 * original word is kept as well, so typos of it still match.
 */
