/**
 * Media for an exercise: its own uploads, otherwise the dataset photos of the system exercise.
 * Nothing is guessed from the name — user-created exercises only get a video search link, and the
 * UI shows the anatomy visual instead of a possibly wrong photo.
 */
export function resolveExerciseMedia(exercise: {
  id?: string | null;
  slug?: string | null;
  name?: string | null;
  primaryMuscleGroup?: MuscleGroup | null;
  media?: ExerciseDto['media'];
  isSystem?: boolean | null;
}): NonNullable<ExerciseDto['media']> {
  if (exercise.media && exercise.media.length > 0) {
    return exercise.media;
  }
  if (exercise.isSystem !== false && exercise.id) {
    const system = CORE_BY_ID.get(exercise.id) ?? getRegisteredExercise(exercise.id);
    if (system?.media && system.media.length > 0) return system.media;
  }
  const rawSlug = (exercise.slug || exercise.id || '').replace(/^ex-/, '').toLowerCase();
  return [exerciseVideoLink(rawSlug, exercise.name || 'Exercise')];
}
