/// In-app copy follows the in-app language preference (System / English / Deutsch), mirroring the
/// web locales, so it can't rely on the bundle's preferred localization alone. English strings are
/// the keys; German lives in `LukiStrings.german`. Missing keys fall back to English.
extension SupportedLocale {
    /// `tr("Start")` → "Starten" in German.
    public func callAsFunction(_ english: String) -> String {
        guard self == .de else { return english }
        return LukiStrings.german[english] ?? english
    }

    /// Format strings use `%@` / `%d` placeholders: `tr("%d sets", count)`.
    public func callAsFunction(_ english: String, _ args: CVarArg...) -> String {
        String(format: self(english), locale: Locale(identifier: rawValue), arguments: args)
    }
}

extension EnvironmentValues {
    /// Resolved app language. Read it as a translator: `@Environment(\.lukiLocale) private var tr`.
    @Entry public var lukiLocale: SupportedLocale = .en
}

